import os
from typing import Dict, List

def artifact_content_reader(artifact_name: str) -> Dict[str, str]:
    """
    Читает содержимое указанного артефакта из локального файла.

    Этот инструмент предназначен для работы в строго контролируемом окружении,
    где артефакты существуют в виде локальных текстовых файлов с предсказуемыми
    именами. Он проверяет, что запрошенный артефакт находится в списке
    разрешенных, а затем пытается прочитать и вернуть его содержимое.

    Предполагается, что файлы артефактов находятся в той же директории,
    где выполняется скрипт, и имеют расширение .txt.

    Args:
        artifact_name (str): Имя артефакта для чтения. Должно быть одним из
                             разрешенных значений:
                             - 'artifact_01_product_definition'
                             - 'artifact_02_roadmap_viz'

    Returns:
        Dict[str, str]: Словарь, содержащий статус операции и данные.
                        В случае успеха: {"status": "success", "data": "содержимое файла..."}

    Raises:
        Exception: Если:
                   - Указано неверное имя артефакта.
                   - Файл артефакта не найден.
                   - Произошла ошибка при чтении файла.
                   - Произошла любая другая непредвиденная ошибка.
    """
    # Список разрешенных для чтения артефактов для обеспечения безопасности и контроля.
    ALLOWED_ARTIFACTS: List[str] = [
        "artifact_01_product_definition",
        "artifact_02_roadmap_viz"
    ]

    # 1. Валидация входных данных
    if artifact_name not in ALLOWED_ARTIFACTS:
        raise Exception(
            f"Недопустимое имя артефакта: '{artifact_name}'. "
            f"Разрешенные имена: {', '.join(ALLOWED_ARTIFACTS)}"
        )

    # 2. Формирование пути к файлу и чтение содержимого
    # Предполагаем, что файлы имеют расширение .txt и находятся в текущей директории.
    file_path = f"{artifact_name}.txt"

    try:
        # Проверяем существование файла перед попыткой чтения
        if not os.path.exists(file_path):
            raise FileNotFoundError(f"Файл артефакта '{file_path}' не найден в текущей директории.")

        # Используем 'with' для безопасного открытия файла и 'utf-8' для совместимости.
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()

        # 3. Возврат успешного результата
        return {"status": "success", "data": content}

    except FileNotFoundError as e:
        # Перехватываем конкретную ошибку и выдаем понятное сообщение.
        raise Exception(str(e))
    except IOError as e:
        # Обработка других ошибок ввода-вывода (например, нет прав на чтение).
        raise Exception(f"Ошибка ввода-вывода при чтении файла '{file_path}': {e}")
    except Exception as e:
        # Общий обработчик для любых других непредвиденных ошибок.
        raise Exception(f"Непредвиденная ошибка при обработке артефакта '{artifact_name}': {e}")