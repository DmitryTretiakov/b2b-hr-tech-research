import requests
import json
from typing import List, Dict, Any, Set

# ЗАПРЕЩЕНО импортировать что-либо еще, кроме стандартных библиотек Python.
# from bs4 import BeautifulSoup # BeautifulSoup не требуется для данной задачи, но разрешен.


def hypothesis_filter(projects_to_check: List[str]) -> Dict[str, Any]:
    """
    Фильтрует предоставленный список проектов, удаляя те, которые уже
    присутствуют в эталонном списке "исходных гипотез".

    Этот инструмент выполняет следующие шаги:
    1. Определяет URL-адрес, по которому находится эталонный список
       исходных гипотез. Этот URL является внутренней константой инструмента.
    2. Выполняет HTTP GET-запрос для получения этого списка. Список
       представляет собой текстовый файл, где каждая гипотеза находится на новой строке.
    3. Обрабатывает полученный текст, преобразуя его в множество (Set) для
       быстрого и эффективного поиска. Пустые строки и лишние пробелы игнорируются.
    4. Сравнивает каждый элемент из входного списка `projects_to_check` с
       эталонным множеством.
    5. Возвращает словарь, содержащий отфильтрованный список проектов,
       которые НЕ были найдены в эталонном списке.

    Args:
        projects_to_check (List[str]): Список названий проектов, которые
                                       необходимо проверить на уникальность
                                       относительно исходных гипотез.

    Returns:
        Dict[str, Any]: Словарь со статусом выполнения и результатом.
                        В случае успеха:
                        {
                            "status": "success",
                            "data": ["Новый проект 1", "Новый проект 2", ...]
                        }
                        где "data" - это список проектов, отсутствующих в
                        эталонном списке.

    Raises:
        Exception: Вызывается в случае сетевых ошибок (недоступность URL,
                   ошибки HTTP) или любых других непредвиденных проблем
                   в процессе выполнения. Сообщение об ошибке содержит
                   детали для дальнейшей диагностики.
    """
    # URL, по которому хранится эталонный список гипотез.
    # Это может быть ссылка на raw-файл в GitHub, Gist, или простой текстовый файл на сервере.
    # Использование такого подхода делает инструмент гибким, так как список можно
    # обновлять без изменения кода самого инструмента.
    SOURCE_HYPOTHESES_URL = "https://gist.githubusercontent.com/ai-tool-builder/a515a85c18cb7523178333335a811833/raw/hypothesis_source_list.txt"

    try:
        # Шаг 1: Получение эталонного списка гипотез
        try:
            response = requests.get(SOURCE_HYPOTHESES_URL, timeout=15)
            # Проверяем, что запрос завершился успешно (статус 2xx)
            response.raise_for_status()
        except requests.exceptions.RequestException as e:
            # Обработка всех сетевых ошибок: таймаут, проблемы с DNS, HTTP ошибки и т.д.
            raise Exception(
                f"Сетевая ошибка при получении списка исходных гипотез с URL "
                f"'{SOURCE_HYPOTHESES_URL}': {e}"
            )

        # Шаг 2: Обработка и преобразование списка в множество для эффективности
        # .strip() удаляет начальные/конечные пробелы со всего текста
        # .split('\n') разделяет текст на строки
        # line.strip() удаляет пробелы с каждой отдельной строки
        # `if line.strip()` отфильтровывает пустые строки, которые могут появиться
        initial_hypotheses: Set[str] = {
            line.strip() for line in response.text.strip().split('\n') if line.strip()
        }

        if not initial_hypotheses:
            # Если эталонный список по какой-то причине оказался пуст,
            # это может быть ошибкой в данных. Вызываем исключение.
            raise Exception(f"Эталонный список гипотез, полученный с {SOURCE_HYPOTHESES_URL}, пуст.")

        # Шаг 3: Фильтрация входного списка
        # Создаем новый список, содержащий только те проекты,
        # которых нет в множестве initial_hypotheses.
        # Проверка `p not in initial_hypotheses` очень быстрая благодаря использованию Set.
        new_projects: List[str] = [
            p for p in projects_to_check if p not in initial_hypotheses
        ]

        # Шаг 4: Возврат успешного результата
        return {
            "status": "success",
            "data": new_projects
        }

    except Exception as e:
        # Перехватываем либо наше собственное исключение, либо любое другое,
        # которое могло произойти, и "пробрасываем" его выше.
        # Это гарантирует, что вызывающий код получит стандартизированную ошибку.
        raise Exception(f"Ошибка в инструменте hypothesis_filter: {e}")